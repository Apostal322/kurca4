"""Independent audit of the reported results (Task 1 of the continuation).

Each check recomputes a claim from scratch, as far as possible with code paths
different from the ones that produced the results, and records PASS/FAIL with
the measured numbers in results/audit/audit_report.md.
"""
import json
from pathlib import Path
from unittest import mock

import numpy as np
from scipy.interpolate import AAA, PchipInterpolator

import qscatter.data as data_mod
import qscatter.experiments.adaptive as adaptive_mod
from qscatter.config import STAGE_A, STAGE_B
from qscatter.data import TrainingSet, make_training_set
from qscatter.experiments.adaptive import run_strategy
from qscatter.physics.analytic import single_barrier_T
from qscatter.physics.ode_solver import solve_ode
from qscatter.physics.potentials import from_layers
from qscatter.physics.resonances import find_resonances
from qscatter.physics.smatrix import compute_scattering, compute_transmission

OUT = Path("results/audit")
OUT.mkdir(parents=True, exist_ok=True)
lines = ["# Audit of the reported results", "",
         "Generated by `scripts/audit.py`. Every check recomputes the claim independently.", ""]
summary = []


def record(name, ok, detail):
    summary.append((name, ok))
    lines.append(f"## {'PASS' if ok else 'FAIL'} — {name}\n\n{detail}\n")
    print(("PASS " if ok else "FAIL ") + name, flush=True)


rng = np.random.default_rng(2026)

# 1. probability conservation on the actual reference grids + random multilayer potentials
worst = {}
for P in (STAGE_A, STAGE_B):
    E = np.linspace(*P.E_range, P.n_ref)
    worst[P.name] = float(np.max(compute_scattering(E, P.potential()).unitarity_defect))
rand_worst = 0.0
for _ in range(50):
    n = rng.integers(1, 8)
    pot = from_layers(rng.uniform(0.05, 1.5, n), rng.uniform(-5, 30, n))
    E = np.sort(rng.uniform(1e-3, 40, 2000))
    rand_worst = max(rand_worst, float(np.max(compute_scattering(E, pot).unitarity_defect)))
record("1. Probability conservation |T+R-1|",
       max(worst.values()) < 1e-12 and rand_worst < 1e-12,
       f"Reference grids: {worst}. 50 random multilayer potentials (1–7 layers, V in [-5, 30]): max {rand_worst:.1e}.")

# 2. analytic single barrier, many (V0, a)
err = 0.0
for _ in range(100):
    V0, a = rng.uniform(0.5, 30), rng.uniform(0.1, 3)
    E = rng.uniform(1e-3, 3 * V0, 500)
    pot = from_layers([a], [V0])
    err = max(err, float(np.max(np.abs(compute_transmission(E, pot) - single_barrier_T(E, V0, a)))))
record("2. Single barrier vs textbook formula (100 random (V0, a), 500 energies each)", err < 1e-11,
       f"max |T - T_analytic| = {err:.1e}")

# 3. ODE agreement: random energies + all resonance peaks + half-maximum points
pB = STAGE_B.potential()
res = find_resonances(lambda e: compute_transmission(e, pB), np.linspace(*STAGE_B.E_range, 200001))
Es = list(rng.uniform(*STAGE_B.E_range, 40)) + [r.E_res for r in res] + [r.E_lo for r in res] + [r.E_hi for r in res]
d = [abs(solve_ode(e, pB).t - compute_scattering(e, pB).t[0]) for e in Es]
record("3. S-matrix vs independent ODE solver (Stage B, 40 random E + peaks + half-max points)", max(d) < 1e-8,
       f"max |t_S - t_ODE| = {max(d):.1e}, median {np.median(d):.1e}")

# 4. resonance positions and widths: (a) ODE-only peak search, (b) complex poles of a rational fit
from scipy.optimize import brentq, minimize_scalar

rows4 = []
ok4 = True
for r in res:
    fo = lambda e: abs(solve_ode(float(e), pB).t) ** 2
    opt = minimize_scalar(lambda e: -fo(e), bounds=(r.E_res - 0.2 * r.fwhm, r.E_res + 0.2 * r.fwhm),
                          method="bounded", options=dict(xatol=1e-10))
    E_ode = float(opt.x)
    lo = brentq(lambda e: fo(e) - 0.5, r.E_res - 3 * r.fwhm, E_ode, xtol=1e-13)
    hi = brentq(lambda e: fo(e) - 0.5, E_ode, r.E_res + 3 * r.fwhm, xtol=1e-13)
    # pole of t in the complex-k plane from a rational (AAA) fit on a local real-axis window
    k_w = np.sqrt(np.linspace(r.E_res - 6 * r.fwhm, r.E_res + 6 * r.fwhm, 400))
    aaa = AAA(k_w, compute_scattering(k_w**2, pB).t, rtol=1e-13)
    poles, resid = aaa.poles(), aaa.residues()
    # discard spurious "Froissart doublets" (negligible residue) and non-physical poles:
    # resonances are poles of t(k) in the lower half of the complex k-plane
    phys = (np.abs(resid) > 1e-10) & (poles.imag < 0)
    poles = poles[phys]
    kp = poles[np.argmin(np.abs(poles - np.sqrt(r.E_res)))]
    Ep = kp**2  # pole in the complex-E plane: E_r - i Gamma/2
    rows4.append((r.E_res, E_ode, r.fwhm, hi - lo, Ep.real, -2 * Ep.imag))
    ok4 &= abs(E_ode - r.E_res) < 1e-6 * r.fwhm + 1e-9 and abs((hi - lo) - r.fwhm) < 1e-7 * r.fwhm
tab = "| E_res (S-matrix) | E_res (ODE) | FWHM (S-matrix) | FWHM (ODE) | Re E_pole | −2 Im E_pole |\n|---|---|---|---|---|---|\n"
tab += "\n".join(f"| {a:.9f} | {b:.9f} | {c:.6e} | {dd:.6e} | {e:.6f} | {f:.6e} |" for a, b, c, dd, e, f in rows4)
record("4. Resonance positions and widths", ok4,
       tab + "\n\nThe ODE-only peak search and half-maximum crossings reproduce the S-matrix values. "
       "The complex pole of t(k) (rational AAA fit on a real-axis window) gives Γ_pole = −2 Im E_pole, which agrees "
       "with the FWHM to within the asymmetry caused by the non-resonant background (largest for the broad resonance).")

# 5 + 6. adaptive sampling validity and absence of reference leakage
calls = {"n": 0}
real_cs = adaptive_mod.CountingSolver


def poisoned_reference(*a, **k):
    raise AssertionError("reference solution accessed during acquisition")


with mock.patch.object(data_mod, "reference_solution", poisoned_reference), \
        mock.patch("qscatter.experiments.sample_efficiency._ref", poisoned_reference):
    designs = {s: run_strategy(STAGE_B, s, (10, 20, 40, 80, 160, 320)) for s in ("segment_T", "segment_t")}
    designs["gp_std"] = run_strategy(STAGE_B, "gp_std", (10, 20, 40))
ok56 = True
det = []
for s, dd in designs.items():
    for N, ts in dd.items():
        ok56 &= len(ts) == N == ts.n_evals and len(np.unique(ts.E)) == N
        # every stored value must equal a fresh exact evaluation at that energy
        ok56 &= np.array_equal(ts.t, compute_scattering(ts.E, pB).t)
    det.append(f"{s}: N={list(dd)}")
record("5/6. Adaptive designs: evaluation counts, stored values, no access to the reference", ok56,
       "Acquisition was re-run with `reference_solution` and the experiment reference cache replaced by functions "
       "that raise on access; no access occurred. Stored t-values are bit-identical to fresh solver calls; "
       "every point is unique; N == n_evals. " + "; ".join(det))

# 10a. reproducibility of designs: re-run vs saved
same = all(np.array_equal(designs[s][N].E, TrainingSet.load(f"results/exp2/designs/double_barrier_{s}_N{N}_s0").E)
           for s in ("segment_T", "segment_t") for N in (20, 80, 320))
record("10a. Adaptive designs reproduce bit-for-bit", same, "segment_T / segment_t, N = 20, 80, 320.")

# 7. RMSE recomputation from saved designs with independent code
rows = [json.loads(l) for l in Path("results/exp2/raw_results.jsonl").read_text().splitlines()]
E_ref = np.linspace(*STAGE_B.E_range, STAGE_B.n_ref)
T_ref = np.abs(compute_scattering(E_ref, pB).t) ** 2
max_rel = 0.0
for r in rows:
    if r["problem"] == "double_barrier" and r["recon"] == "pchip" and r["design_seed"] == 0:
        ts = TrainingSet.load(f"results/exp2/designs/double_barrier_{r['strategy']}_N{r['N']}_s0")
        f_re, f_im = PchipInterpolator(ts.E, ts.t.real), PchipInterpolator(ts.E, ts.t.imag)
        T_hat = f_re(E_ref) ** 2 + f_im(E_ref) ** 2
        rmse = np.sqrt(np.sum((T_hat - T_ref) ** 2) / T_ref.size)
        max_rel = max(max_rel, abs(rmse / r["rmse_T"] - 1))
record("7. RMSE recomputation (Exp. 2, all PCHIP rows, independent implementation)", max_rel < 1e-10,
       f"max relative difference to logged RMSE = {max_rel:.1e}")

# 8. evaluation counts across all logged experiments
bad = 0
for f in ("results/exp1/raw_results.jsonl", "results/exp2/raw_results.jsonl", "results/exp1_mlp_no_es/raw_results.jsonl"):
    for l in Path(f).read_text().splitlines():
        r = json.loads(l)
        bad += r["n_exact_evals"] != r["N"]
record("8. Solver evaluation count equals N in every logged run", bad == 0, f"{bad} mismatches.")

# 9. reference-grid convergence (Stage B resonant windows at 16x the reference density)
fine = np.linspace(STAGE_B.E_range[0], STAGE_B.E_range[1], 16 * (STAGE_B.n_ref - 1) + 1)
Tf = compute_transmission(fine, pB)
ts = make_training_set(STAGE_B, 160, "uniform")
fr, fi = PchipInterpolator(ts.E, ts.t.real), PchipInterpolator(ts.E, ts.t.imag)
r_ref = np.sqrt(np.mean((fr(E_ref) ** 2 + fi(E_ref) ** 2 - T_ref) ** 2))
r_fine = np.sqrt(np.mean((fr(fine) ** 2 + fi(fine) ** 2 - Tf) ** 2))
record("9. Reference-grid convergence (16x finer grid)", abs(r_ref / r_fine - 1) < 1e-3,
       f"RMSE on reference grid {r_ref:.6e}, on 16x finer grid {r_fine:.6e} (rel. diff {abs(r_ref / r_fine - 1):.1e}).")

# 10b. reproducibility of an Exp. 1 MLP row (deterministic training)
import torch

torch.set_num_threads(1)
from qscatter.experiments.sample_efficiency import Exp1Config, run_one

row_old = next(r for r in (json.loads(l) for l in Path("results/exp1/raw_results.jsonl").read_text().splitlines())
               if r["method"] == "mlp" and r["problem"] == "single_barrier" and r["N"] == 20
               and r["sampling"] == "uniform" and r["target"] == "amplitude" and r["seed"] == 1)
cfg = Exp1Config(out_dir="results/audit/tmp_exp1", save_models_seed=-1)
row_new = run_one(("single_barrier", "uniform", 1, 20, "mlp", "amplitude", cfg))
record("10b. Exp. 1 MLP run reproduces (single barrier, N=20, seed 1)",
       row_new["rmse_T"] == row_old["rmse_T"],
       f"logged {row_old['rmse_T']!r}, recomputed {row_new['rmse_T']!r}")

lines.insert(4, "| check | result |\n|---|---|\n" + "\n".join(f"| {n} | {'PASS' if ok else 'FAIL'} |" for n, ok in summary) + "\n")
(OUT / "audit_report.md").write_text("\n".join(lines))
